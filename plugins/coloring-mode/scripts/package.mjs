import { execFileSync } from "node:child_process";
import { rmSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const zip = resolve(root, "plugin-package.zip");
if (!existsSync(resolve(root, "dist/index.js"))) throw new Error("Build output is missing; run npm run build first.");
rmSync(zip, { force: true });
execFileSync("zip", ["-q", "-r", zip, "manifest.json", "dist", "vendor/standalone-coloring-mode", "README.md", "API_CHANGE_REQUEST.md", "INTEGRATION_REPORT.md", "LICENSE"], { cwd: root, stdio: "inherit" });
console.log(`Created ${zip}`);
